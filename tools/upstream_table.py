"""
tools/upstream_table.py -- the full upstream table, generated from the upstream ledger (D-552, D-553).

The table lists every finding reported upstream, not highlights. Unreported findings never appear: the ledger keeps
them in a section of their own, which this tool does not read (D-134). Each row gives the library, what gpconf
found, the status (merged / released / open / declined / closed), a proof link to the most direct evidence (the
merged pull request; else the maintainer's fixing commit; for an open item, the issue), the release link if the fix
has shipped, and the date.

Two inputs:
- the ledger's section 3 ("Grouped"), one bullet per finding under four headings. The ledger is private; the
  maintainer runs `rows` from it and commits the result, `docs/upstream/table.json`, which is public;
- the recorded GitHub facts, `docs/upstream/github-facts.json`: what GitHub answered for each link (state, merged,
  dates, release tags), written by `tools/check_upstream_table.py --record`. They fill what the ledger leaves out (an
  open issue's report date, a release's link) and are what the check compares GitHub with.

Usage:
  python3 tools/upstream_table.py rows --ledger LEDGER [--facts FACTS] --out docs/upstream/table.json
  python3 tools/upstream_table.py render --table docs/upstream/table.json      # the markdown table, to stdout
  python3 tools/upstream_table.py inject --table docs/upstream/table.json FILE ...   # between the markers
A row the tool cannot complete (no proof link, no date) is listed as a gap; `rows` exits 1 while any gap is left,
unless --allow-gaps.
"""
import argparse
import json
import os
import re
import sys

GROUPS = (  # the ledger's headings, in its order, and the group each names
    ("Fixed by my pull requests", "my-pr"),
    ("Fixed by maintainers and contributors after my report", "maintainer"),
    ("Reported, still open", "open"),
    ("Ended another way", "other"),
)
SECTION = "## 3. Grouped"
BEGIN = "<!-- upstream-table:begin (generated by tools/upstream_table.py from docs/upstream/table.json; do not edit) -->"
END = "<!-- upstream-table:end -->"
LINK = re.compile(r"\[([^\]]+)\]\((https://github\.com/[^)\s]+)\)")
GH = re.compile(r"^https://github\.com/([^/]+)/([^/]+)/(issues|pull|commit|releases/tag)/([^/?#]+)")


def kind_of(url):
    m = GH.match(url)
    if not m:
        return None
    return {"issues": "issue", "pull": "pr", "commit": "commit", "releases/tag": "release"}[m.group(3)]


def repo_of(url):
    m = GH.match(url)
    return f"{m.group(1)}/{m.group(2)}" if m else None


def section_3(text):
    """The lines of the ledger's section 3, up to the next section."""
    i = text.find(SECTION)
    if i < 0:
        raise ValueError("the ledger has no section 3 (Grouped)")
    j = text.find("\n## ", i + len(SECTION))
    return text[i:j if j >= 0 else len(text)].splitlines()


def parse_ledger(text):
    """-> (rows, counts): one row per finding bullet under the four headings, and each heading's stated count."""
    rows, counts, group = [], {}, None
    for line in section_3(text):
        h = re.match(r"^#### (.+?) \((\d+)\)\s*$", line)
        if h:
            names = dict(GROUPS)
            group = names.get(h.group(1))
            if group:
                counts[group] = int(h.group(2))
            continue
        if line.startswith("#### "):
            group = None   # "Per library" and anything after it hold notes, not findings
            continue
        if group and line.startswith("- **"):
            rows.append(parse_bullet(line, group))
    return rows, counts


def parse_bullet(line, group):
    m = re.match(r"^- \*\*(.+?)\*\*:\s*(.*)$", line)
    if not m:
        raise ValueError(f"not a finding bullet: {line[:80]}")
    library, rest = m.group(1).strip(), m.group(2)
    # "Private notes: ..." runs to the end of the bullet and is never read, stored or rendered (D-560)
    rest = re.split(r"\s*Private notes:", rest, maxsplit=1)[0]
    status_given = re.search(r";?\s*status: (closed \(maintainers said planned\)|merged; the project has no releases|another user's report, open upstream)\.?", rest)
    if status_given:
        rest = rest.replace(status_given.group(0), ".")
    # an explicit proof ("proof: [text](url)") and a link the ledger itself marks as inferred
    # ("likely fixing commit (inferred: why): [text](url)", D-558) are taken out first
    given = re.search(r"proof: \[([^\]]+)\]\((https://github\.com/[^)\s]+)\)", rest)
    inf = re.search(r"(likely [^:;(]+ \(inferred: [^)]+\)): \[([^\]]+)\]\((https://github\.com/[^)\s]+)\)", rest)
    scan = rest
    for x in (inf, given):
        if x:
            scan = scan.replace(x.group(0), "")
    links = [(t, u) for t, u in LINK.findall(scan)]
    first = LINK.search(rest)
    finding = (rest[:first.start()] if first else rest).strip().rstrip(".").strip()
    involvement = None
    inv = re.search(r";\s*involvement: (.+)$", finding)
    if inv:   # what gpconf did where it did not find the issue (D-560): the table never claims more
        involvement, finding = inv.group(1).strip().rstrip("."), finding[:inv.start()].strip()
    tail = scan[LINK.search(scan).start():] if LINK.search(scan) else ""
    issues = [u for _, u in links if kind_of(u) == "issue"]
    prs = [u for _, u in links if kind_of(u) == "pr"]
    commits = [u for _, u in links if kind_of(u) == "commit"]
    rel = re.search(r"released in (\[([^\]]+)\]\((https://github\.com/[^)\s]+)\)|([\w.\-]+))"
                    r"(?: \(([\w.\-]+) not counted: ([^()]+)\))?", tail)
    release = None
    if rel:
        release = {"name": (rel.group(2) or rel.group(4)).rstrip("."), "url": rel.group(3)}
        if rel.group(5):
            # an earlier release that holds the fix but is not counted, with the reason, shown in the table; the
            # check passes it only if that release is exactly the one before, and fails it once it is not needed
            release["not_counted"] = {"tag": rel.group(5), "why": rel.group(6).strip()}
    # a fix the maintainer's record marks as an opt-in (D-593): "opt-in `NAME`", optionally "for SCOPE", as a clause of
    # its own (after a link, a comma, a semicolon or a parenthesis), so "not an opt-in `x`" is no mark; the table then
    # says the fix is an opt-in and the default behaviour is unchanged, as the record does. The check confirms only that
    # the name is in the upstream's own words; it cannot see an opt-in the record does not mark
    oi = re.search(r"(?:^|[,;(]\s*|\)\s*)opt-in `([^`]+)`(?: for ([^,;.()]+))?", tail)
    merged = re.search(r"merged (\d{4}-\d{2}-\d{2})", tail)
    by = re.search(r"fixed by ([^,;]+(?:, (?:the maintainer|a contributor))?)", tail)
    given_status = {"closed (maintainers said planned)": "closed-planned",
                    "merged; the project has no releases": "merged-no-releases",
                    "another user's report, open upstream": "open-others-report"}.get(status_given.group(1)) if status_given else None
    if given_status:
        status = given_status
    elif group in ("my-pr", "maintainer"):
        status = "released" if release else "merged"
    elif group == "open":
        status = "open"
    else:
        status = ("declined" if re.search(r"closed by the maintainer without a change", tail)
                  else "unclassified" if re.search(r"\bclosed by\b", tail) else "open")   # a close must say why
    return {"group": group, "library": library, "finding": finding, "issues": issues, "prs": prs, "commits": commits,
            "status": status, "release": release, "merged": merged.group(1) if merged else None,
            "by": by.group(1).strip() if by else None, "involvement": involvement,
            "proof_given": {"text": given.group(1), "url": given.group(2)} if given else None,
            "inferred": {"label": inf.group(1), "text": inf.group(2), "url": inf.group(3)} if inf else None,
            "opt_in": {"name": oi.group(1), "scope": (oi.group(2) or "").strip() or None} if oi else None}


def complete(rows, facts):
    """Fill each row's proof, release link and date from the ledger, then from the recorded GitHub facts. -> gaps."""
    facts = facts or {}
    gaps = []
    for r in rows:
        fixed = r["group"] in ("my-pr", "maintainer")
        if r.get("proof_given"):
            r["proof"] = r["proof_given"]["url"]
        elif fixed:
            # the merged pull request; else the maintainer's fixing commit (D-552)
            merged_prs = [u for u in r["prs"] if facts.get(u, {}).get("merged")]
            if merged_prs:
                r["proof"] = merged_prs[-1]
            elif r["prs"]:
                r["proof"] = r["prs"][-1]   # the ledger names it as the fix; the check confirms it is merged
            elif r["commits"]:
                r["proof"] = r["commits"][0]
            elif r["issues"]:
                r["proof"] = facts.get(r["issues"][0], {}).get("closing_commit")
            else:
                r["proof"] = None
        else:
            r["proof"] = r["issues"][0] if r["issues"] else (r["prs"][0] if r["prs"] else None)
        if r["release"] and not r["release"].get("url"):
            repo = repo_of(r["proof"] or (r["issues"] + r["prs"] + [""])[0]) or ""
            for tag in (r["release"]["name"], r["release"]["name"].lstrip("v"), "v" + r["release"]["name"].lstrip("v")):
                u = f"https://github.com/{repo}/releases/tag/{tag}"
                if facts.get(u, {}).get("exists"):
                    r["release"]["url"] = u
                    break
        if fixed and kind_of(r["proof"] or "") == "release":
            r["date"] = (facts.get(r["proof"], {}).get("published_at") or "")[:10] or None
            r["date_is"] = "released"
        elif fixed:
            r["date"] = r["merged"] or (facts.get(r["proof"] or "", {}).get("merged_at") or "")[:10] or None
            r["date_is"] = "merged"
        elif r["status"] in ("declined", "closed-planned", "unclassified"):
            r["date"] = (facts.get(r["proof"] or "", {}).get("closed_at") or "")[:10] or None
            r["date_is"] = "closed"
        else:
            r["date"] = (facts.get(r["proof"] or "", {}).get("created_at") or "")[:10] or None
            r["date_is"] = "reported"
        missing = [k for k, v in (("proof link", r["proof"]), ("date", r["date"])) if not v]
        if r["status"] not in STATUS_WORD:
            missing.append(f"allowed status (the ledger says {r['status']!r})")
        if r["release"] and not r["release"].get("url"):
            missing.append(f"release link for {r['release']['name']}")
        if missing:
            gaps.append(f"{r['library']}: {r['finding'][:60]}: no {', no '.join(missing)}")
    return gaps


def link(url, text=None):
    if not url:
        return ""
    if text is None:
        k, m = kind_of(url), GH.match(url)
        text = {"issue": f"#{m.group(4)}", "pr": f"PR #{m.group(4)}", "commit": m.group(4)[:7],
                "release": m.group(4)}.get(k, url) if m else url
    return f"[{text}]({url})"


# the allowed statuses (D-552, D-560); anything else is a gap in `rows` and a mismatch in the check
STATUS_WORD = {"released": "released", "merged": "merged, not yet released",
               "merged-no-releases": "merged; the project has no releases", "open": "open", "declined": "declined",
               "closed-planned": "closed (maintainers said planned)",
               "open-others-report": "another user's report, open upstream"}   # counted apart from this project's open reports


def opt_in_clause(r):
    """The plain words for a fix the record marks as an opt-in (D-593): it exists, it is an opt-in, the default behaviour is unchanged."""
    oi = r.get("opt_in")
    if not oi:
        return ""
    where = f"for {oi['scope']}, " if oi.get("scope") else ""
    return f"; {where}the fix is an opt-in (`{oi['name']}`), and the default behaviour is unchanged"


def render(table):
    rows = table["rows"]
    out = ["| library | finding | status | proof | release | date |", "|---|---|---|---|---|---|"]
    for r in rows:
        finding = (r["finding"] + opt_in_clause(r) + (f" ({r['involvement']})" if r.get("involvement") else "")).replace("|", "\\|")
        rel = link(r["release"]["url"], r["release"]["name"]) if r.get("release") and r["release"].get("url") else (
            r["release"]["name"] if r.get("release") else "")
        nc = (r.get("release") or {}).get("not_counted")
        if nc:
            rel += f" ({nc['tag']} not counted: {nc['why']})".replace("|", "\\|")
        date = f"{r['date']} ({r['date_is']})" if r.get("date") else ""
        proof = link(r.get("proof"), (r.get("proof_given") or {}).get("text"))
        if r.get("inferred"):
            proof += f"; {r['inferred']['label']}: {link(r['inferred']['url'], r['inferred']['text'])}"
        out.append(f"| {r['library']} | {finding} | {STATUS_WORD[r['status']]} | {proof} | {rel} | {date} |")
    s = table["summary"]
    theirs = sum(1 for r in table["rows"] if r["status"] == "open-others-report")   # another user's report, counted apart
    others = (f"{s['other']} that ended another way" if not theirs else
              f"{s['other']} others: {s['other'] - theirs} that ended another way and {theirs} another user's report" + ("s" if theirs > 1 else ""))
    out += ["", f"{s['total']} findings: {s['my-pr']} fixed by this project's pull requests, {s['maintainer']} by maintainers and "
            f"contributors after this project's report, {s['open']} still open, {others}; as of {table['as_of']}."]
    return "\n".join(out) + "\n"


def inject(path, block):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise ValueError(f"{path}: no upstream-table markers")
    new = text[:i + len(BEGIN)] + "\n" + block + text[j:]
    if new != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
    return new != text


def main(argv=None):
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("rows"); a.add_argument("--ledger", required=True); a.add_argument("--facts")
    a.add_argument("--out", required=True); a.add_argument("--as-of", required=True); a.add_argument("--allow-gaps", action="store_true")
    b = sub.add_parser("render"); b.add_argument("--table", required=True)
    c = sub.add_parser("inject"); c.add_argument("--table", required=True); c.add_argument("files", nargs="+")
    args = ap.parse_args(argv)
    if args.cmd == "rows":
        rows, counts = parse_ledger(open(args.ledger, encoding="utf-8").read())
        got = {g: sum(1 for r in rows if r["group"] == g) for _, g in GROUPS}
        if got != counts:
            print(f"the ledger's headings say {counts}, its bullets give {got}", file=sys.stderr)
            return 1
        facts = json.load(open(args.facts, encoding="utf-8")) if args.facts and os.path.exists(args.facts) else {}
        gaps = complete(rows, facts)
        table = {"generated_by": "tools/upstream_table.py (D-552, D-553)", "as_of": args.as_of,
                 "summary": dict(got, total=len(rows)), "rows": rows}
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump(table, f, indent=1, ensure_ascii=False)
            f.write("\n")
        for g in gaps:
            print("gap:", g, file=sys.stderr)
        print(f"{len(rows)} rows ({got}); {len(gaps)} gap(s)")
        return 1 if gaps and not args.allow_gaps else 0
    table = json.load(open(args.table, encoding="utf-8"))
    if args.cmd == "render":
        sys.stdout.write(render(table))
        return 0
    block = render(table)
    for p in args.files:
        print(("updated " if inject(p, block) else "unchanged ") + p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
